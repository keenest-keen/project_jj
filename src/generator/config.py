# ============================================================
# Шаблоны URL для ссылок на теги
# ============================================================
def tag_url(slug: str, offset: int = 0) -> str:
    if offset == 0:
        return f"{TAG_DIR_NAME}/{slug}.html"
    return f"{TAG_DIR_NAME}/{slug}-{offset}.html"

def pagination_url(offset: int) -> str:
    if offset == 0:
        return "index.html"
    return f"index-{offset}.html"

